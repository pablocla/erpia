export function getTicketById(id: string): BacklogTicket | undefined {
  return PRODUCT_BACKLOG_CATALOG.find((t) => t.id.toUpperCase() === id.toUpperCase())
}

export function listByAssignee(assignee: BacklogTicket["assignee"]) {
  return PRODUCT_BACKLOG_CATALOG.filter((t) => t.assignee === assignee)
}

export function listByLifecycle(lifecycle: BacklogTicket["lifecycle"]) {
  return PRODUCT_BACKLOG_CATALOG.filter((t) => t.lifecycle === lifecycle)
}

export function listTicketsByWave(wave: BacklogTicket["wave"]) {
  return PRODUCT_BACKLOG_CATALOG.filter((t) => t.wave === wave)
}

export function listTicketsByPriority(priority?: BacklogTicket["priority"]) {
  const list = [...PRODUCT_BACKLOG_CATALOG]
  if (priority) return list.filter((t) => t.priority === priority)
  const order = { P0: 0, P1: 1, P2: 2, P3: 3 }
  return list.sort((a, b) => order[a.priority] - order[b.priority] || a.id.localeCompare(b.id))
}
