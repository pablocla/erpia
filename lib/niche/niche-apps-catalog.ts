/** Apps estrella para vendedor de calle — demo y cierre rápido */
export const CABALLOS_CALLE_APP_IDS = [
  "consorcios",
  "club",
  "plancha",
  "prestamista",
  "garantia",
] as const

export type CaballoCalleAppId = (typeof CABALLOS_CALLE_APP_IDS)[number]

export function isCaballoCalle(appId: string): boolean {
  return (CABALLOS_CALLE_APP_IDS as readonly string[]).includes(appId)
}

export const NICHE_APP_IDS = NICHE_APPS.map((a) => a.appId)

export function getNicheApp(appId: string): NicheAppDefinition | undefined {
  return NICHE_APPS.find((a) => a.appId === appId)
}

export function getNicheAppBySku(sku: string): NicheAppDefinition | undefined {
  return NICHE_APPS.find((a) => a.sku === sku)
}
